# encoding: utf-8
"""
CubeFramework transport and the native Rust Cortex-M4 image.

Enabled by the board (hwdef "env RUST_M4 1": CubeOrangePlus-SimOnHardWare-M4Rust)
or, on SITL, by --enable-rust-m4. On ChibiOS the M4 image is a separate
ChibiOS RT program built with make (libraries/AP_RustM4/m4/chibios/Makefile);
on SITL it is a host program the M7 SITL runs as a second process.

AP_FLAKE8_CLEAN
"""

from waflib.Configure import conf

CUBEFRAMEWORK = 'modules/CubeFramework'
CF_SOURCES = ['CubePilotFW/Channel.cpp', 'CubePilotFW/SpscRing.cpp', 'CubePilotFW/PeerHeader.cpp']
CF_CHIBIOS_SOURCES = CF_SOURCES + ['CubePilotFW/pal/HSEM.cpp']
CF_POSIX_SOURCES = CF_SOURCES + ['CubePilotFW/pal/Posix.cpp', 'CubePilotFW/pal/PosixHSEM.cpp',
                                 'CubePilotFW/pal/PosixChannel.cpp']
# CubeFramework headers need C++17 (std::atomic<T>::is_always_lock_free). Only the objects that
# include them get it: CubeFramework itself, the M4 process and the AP_RustM4 library objects
# (configure()); the rest of the M7 build stays on ArduPilot's gnu++11. The later -std wins
CXX17_CXXFLAGS = ['-std=gnu++17']
# CubeFramework keeps its own warning set, not ArduPilot's -Werror list
CF_CXXFLAGS = CXX17_CXXFLAGS + ['-Wno-error', '-Wno-cast-align', '-Wno-shadow']
M4_DIR = 'libraries/AP_RustM4/m4'
# the local set the M4 answers itself: generated by rust_bindings (libraries/AP_Rust/wscript)
M4_GENERATED = ['libraries/AP_Rust/BindingMath_generated.cpp', 'libraries/AP_Rust/BindingLocal_generated.cpp']
# the PR's loader, compiled unchanged into the M4 image and the SITL M4 process
M4_PR_SOURCES = ['libraries/AP_Rust/Image.cpp']


def _cf(paths):
    return ['%s/%s' % (CUBEFRAMEWORK, path) for path in paths]


def configure(cfg):
    env = cfg.env
    if cfg.srcnode.find_node(CUBEFRAMEWORK + '/CubePilotFW/Channel.h') is None:
        cfg.fatal('CubeFramework missing: git submodule update --init ' + CUBEFRAMEWORK)
    env.prepend_value('INCLUDES', [cfg.srcnode.find_dir(CUBEFRAMEWORK).abspath()])
    # per-library flags (ap_library.custom_flags_check): AP_RustM4's M7 sources include CubeFramework
    env.AP_LIB_EXTRA_CXXFLAGS['AP_RustM4'] = list(CXX17_CXXFLAGS)
    env.DEFINES += ['AP_CUBEFRAMEWORK_ENABLED=1']


@conf
def cubeframework(bld):
    '''M7 side of the CubeFramework transport, as a static library'''
    if bld.env.BOARD_CLASS == 'ChibiOS':
        # the ring frame CRC is off on the board: the M4 Makefile defines the same value
        return bld.stlib(name='cubeframework', target='cubeframework',
                         source=_cf(CF_CHIBIOS_SOURCES), features=['ch_ap_library'],
                         defines=['USE_CHIBIOS=1', 'CF_SPSC_RING_CRC=0'], includes=[bld.bldnode.abspath()],
                         cxxflags=CF_CXXFLAGS,
                         use=[])  # ap_library's compile database dry run reads .use
    # HSEM.h picks the M7 semaphore mapping from __CORTEX_M
    return bld.stlib(name='cubeframework', target='cubeframework',
                     source=_cf(CF_POSIX_SOURCES), defines=['__CORTEX_M=7'],
                     cxxflags=CF_CXXFLAGS, use=[])


@conf
def rust_m4_image(bld):
    '''the Cortex-M4 image (ChibiOS) or the M4 process (SITL), in bin/'''
    if bld.env.BOARD_CLASS == 'ChibiOS':
        _chibios_image(bld)
    else:
        _sitl_program(bld)
    bld.add_pre_fun(_add_image_target)


def _add_image_target(bld):
    # the image is no vehicle's dependency; build it with any targeted build (run after
    # the build commands have set bld.targets)
    if bld.targets:
        # cubeframework first: posted from inside a vehicle library's use processing,
        # this stlib runs the compile database dry run there, which posts the other
        # targets; a test program's use of 'ap' then clears dronecan_libs'
        # tmp_use_objects and the vehicle library is archived without DroneCAN
        bld.targets = 'cubeframework,' + bld.targets + ',rust_m4_image'


def _chibios_image(bld):
    src = bld.srcnode
    makefile = src.find_node(M4_DIR + '/chibios/Makefile')
    sources = (src.ant_glob(M4_DIR + '/**/*') +
               src.ant_glob('libraries/AP_RustM4/AP_RustM4_*.h') +
               src.ant_glob('libraries/AP_Rust/Image.*') +
               src.ant_glob(CUBEFRAMEWORK + '/CubePilotFW/**/*.h') +
               [src.find_node(path) for path in _cf(CF_CHIBIOS_SOURCES)] +
               [bld.bldnode.find_or_declare(path) for path in M4_GENERATED])
    out = bld.bldnode.make_node('rust_m4')
    generated_root = bld.bldnode.make_node('libraries')
    bin_dir = bld.bldnode.make_node('bin')
    targets = [bin_dir.find_or_declare('rust_m4.elf'), bin_dir.find_or_declare('rust_m4.bin')]
    rule = ("'%s' -s -j%u -f '%s' CHIBIOS='%s' AP_ROOT='%s' BUILDDIR='%s' M4_GENERATED_ROOT='%s' && "
            "mkdir -p '%s' && cp '%s/rust_m4.elf' '%s/rust_m4.bin' '%s'") % (
        bld.env.get_flat('MAKE'), bld.options.jobs, makefile.abspath(),
        src.find_dir('modules/ChibiOS').abspath(), src.abspath(), out.abspath(), generated_root.abspath(),
        bin_dir.abspath(), out.abspath(), out.abspath(), bin_dir.abspath())
    bld(rule=rule, source=sources, target=targets, name='rust_m4_image')


def _sitl_program(bld):
    # m4/*.cpp is the portable runtime, m4/sitl/ the process around it; the shim directory
    # comes first so the real headers' AP includes resolve to it
    runtime = [node.path_from(bld.srcnode) for node in bld.srcnode.ant_glob(M4_DIR + '/*.cpp')]
    sitl = [node.path_from(bld.srcnode) for node in bld.srcnode.ant_glob(M4_DIR + '/sitl/*.cpp')]
    local = [node.path_from(bld.srcnode) for node in bld.srcnode.ant_glob(M4_DIR + '/local/*.cpp')]
    generated = [bld.bldnode.find_or_declare(path) for path in M4_GENERATED]
    bld.program(target='bin/rust_m4', name='rust_m4_image',
                source=runtime + sitl + local + M4_PR_SOURCES + generated + _cf(CF_POSIX_SOURCES),
                includes=[M4_DIR + '/shim', M4_DIR, 'libraries/AP_RustM4', 'libraries', CUBEFRAMEWORK],
                defines=['__CORTEX_M=4', 'AP_RUST_M4_FAULT_INJECTION_ENABLED=1'], cxxflags=CF_CXXFLAGS,
                linkflags=['-pthread'], use=[])
