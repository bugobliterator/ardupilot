"""Renode tests of MAVLink on M4 scripts on the CubeOrangePlus: mavlink_test.lua with a mavgen
subset of the MAVLink module, gcs:run_command_int arming and mode changes, a 21-value logger:write,
and MAV_CMD_SCRIPTING stop and restart, which restart the M4 without spending the fault budget.
Functional only: Renode is not cycle-accurate.

Needs RENODE and a CubeOrangePlus-M4Lua build:
  ./waf configure --board CubeOrangePlus-M4Lua && ./waf copter
"""

